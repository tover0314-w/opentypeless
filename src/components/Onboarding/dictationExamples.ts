export function dictationExampleText(index: number, language: string): string {
  const example = DICTATION_EXAMPLES[index]
  if (!example) return ''
  const locale = language.toLowerCase().split(/[-_]/)[0] as keyof typeof example
  return locale !== 'id' && Object.prototype.hasOwnProperty.call(example, locale)
    ? example[locale]
    : example.en
}
